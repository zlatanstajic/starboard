    /**
     * Resolves the platform from a URL by case-insensitive domain substring,
     * or null when no known platform matches.
     */
    public static function fromUrl(string $url): ?self
    {
        $host = mb_strtolower((string) parse_url($url, PHP_URL_HOST));

        if ($host === '') {
            return null;
        }

        foreach (self::cases() as $case) {
            foreach ($case->matchDomains() as $domain) {
                if ($host === $domain || str_ends_with($host, '.'.$domain)) {
                    return $case;
                }
            }
        }

        return null;
    }

